def find_coord_for_node_key(node_key):
    s = str(node_key)
    if s in coords:
        return coords[s]

    if s.isdigit():
        k = "n" + s
        if k in coords:
            return coords[k]

    if s.startswith("n") and s[1:].isdigit():
        k = s[1:]
        if k in coords:
            return coords[k]
    return None

